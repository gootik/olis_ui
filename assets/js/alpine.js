/** Register Alpine state used by HeroUI components before calling Alpine.start(). */
export function registerHeroUIAlpine(Alpine) {
  registerHeroColorField(Alpine);
  registerHeroSheet(Alpine);
  registerHeroDropdown(Alpine);
  registerHeroDialog(Alpine);
  Alpine.data('heroTimeField', heroTimeField);
  Alpine.data('heroAutocomplete', heroAutocomplete);
  registerHeroComboBox(Alpine);
  registerHeroListbox(Alpine);
  registerHeroAvatarImage(Alpine);
  registerHeroInputGroup(Alpine);
  registerHeroSelect(Alpine);
  registerHeroScrollShadow(Alpine);
  registerHeroToolbar(Alpine);
  registerHeroToastRegion(Alpine);
  registerHeroTooltip(Alpine);
  registerHeroTagGroup(Alpine);
  registerHeroInputOTP(Alpine);
  registerHeroSlider(Alpine);
  registerHeroPopover(Alpine);
  registerHeroDrawer(Alpine);
  registerHeroSearchField(Alpine);
  registerHeroNumberField(Alpine);
  registerHeroTabs(Alpine);
  registerHeroToggleButtonGroup(Alpine);
  registerHeroAccordion(Alpine);
  registerHeroDisclosure(Alpine);
}
